"""Generate the sync of the engine's data into the game's image: every engine data object the image exports
(constants, static members, vtables, typeinfo) that our native engine defines gets the native value copied to its
image address at startup - the game code reads them there. -> out/gen/engine_data.cpp (khux_sync_engine_data)

python tools/gen_engine_data.py [--exclude ns,ns]   # as gen_adapters.py

Vtables copy as they are: the fork's vtables have the game's layout (engine_diff.py), so an image vtable becomes the
native one, slot for slot. The game's own static initializers (the init_array entries that are game code) are
listed too (khux_game_init_array); the library ones are replaced by this copy.
"""
import json, re, struct, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_adapters as G

ROOT, OUT, RECOMP = G.ROOT, G.OUT, G.RECOMP
ENGINE_NS = re.compile(r'^_Z(?:TV|TI|TS)?N?K?(?:7cocos2d|10cocostudio|5spine)|^_ZN7cocos2d|^_ZN10cocostudio|^_ZN5spine')


def image_objects():
    d = (RECOMP / 'game' / 'libcocos2dcpp.so').read_bytes()
    phoff, phnum = struct.unpack_from('<I', d, 0x1C)[0], struct.unpack_from('<H', d, 0x2C)[0]
    dyn = None
    for i in range(phnum):
        t, off, va, pa, fs, ms = struct.unpack_from('<6I', d, phoff + 32 * i)
        if t == 2: dyn = (off, fs)
    tags = {}
    for k in range(0, dyn[1], 8):
        t, v = struct.unpack_from('<2I', d, dyn[0] + k); tags.setdefault(t, v)
    symtab, strtab = tags[6], tags[5]
    n = (strtab - symtab) // 16
    out = []
    for i in range(n):
        nm, val, size, info, other, shndx = struct.unpack_from('<IIIBBH', d, symtab + 16 * i)
        if (info & 0xF) != 1 or not shndx or not size: continue        # STT_OBJECT, defined, sized
        name = d[strtab + nm:d.index(b'\0', strtab + nm)].decode(errors='replace')
        if ENGINE_NS.match(name): out.append((name, val, size))
    return out


def native_data():
    libs = sorted((G.ENGINE / 'lib').glob('*.a'))
    out = subprocess.run([str(G.BIN / 'llvm-nm.exe'), '--defined-only'] + [str(p) for p in libs], capture_output=True, text=True).stdout
    have = set()
    for l in out.splitlines():
        p = l.split()
        if len(p) == 3 and p[1] in 'DdBbRrVv': have.add(p[2])
    return have


def main():
    objs = image_objects()
    have = native_data()
    rows = [(n, v, s) for n, v, s in objs if '_' + n in have]
    ex = G.excluded()
    if ex:
        dem = G.demangle([n for n, v, s in rows])
        def bare(d):
            for pre in ('vtable for ', 'typeinfo for ', 'typeinfo name for ', 'VTT for ', 'guard variable for '):
                if d.startswith(pre): return d[len(pre):]
            return d
        rows = [r for r, d in zip(rows, dem) if not (bare(d) + '::').startswith(ex) and not bare(d).startswith(ex)]
    sys.path.insert(0, str(RECOMP / 'rewrite' / 'tools'))
    import libsplit
    groups = libsplit.groups()
    ia = [int(x, 16) for x in json.loads((RECOMP / 'out' / 'analysis.json').read_text())['init_array']]
    game_ia = [x for x in ia if x and not groups.get(x & ~1)]
    lines = ['// Generated by tools/gen_engine_data.py - do not edit. The engine\'s data copied into the game\'s image.',
             '#include <cstdint>', '#include <cstring>', '']
    for k, (n, v, s) in enumerate(rows):
        lines.append(f'extern "C" const unsigned char d{k}[] __asm__("_{n}");')
    lines += ['', 'static const struct { uint32_t image; uint32_t size; const unsigned char *native; } kData[] = {']
    lines += [f'    {{0x{v:X}, {s}, d{k}}},   // {n}' for k, (n, v, s) in enumerate(rows)]
    lines += ['};', '',
              'extern "C" int khux_sync_engine_data() {',
              '    for (auto &e : kData) std::memcpy(reinterpret_cast<void *>(uintptr_t(e.image)), e.native, e.size);',
              '    return int(sizeof kData / sizeof *kData);', '}', '',
              f'static const uint32_t kGameInit[] = {{{", ".join(hex(x) for x in game_ia)}}};',
              'extern "C" const uint32_t *khux_game_init_array(int *count) { *count = int(sizeof kGameInit / 4); return kGameInit; }', '']
    src = OUT / 'engine_data.cpp'
    src.write_text('\n'.join(lines), encoding='utf-8')
    r = subprocess.run([G.CXX, '-std=gnu++17', '-O1', '-w', '-c', str(src), '-o', str(OUT / 'engine_data.o')], capture_output=True, text=True)
    if r.returncode: sys.exit(r.stderr[-2000:])
    vt = sum(1 for n, v, s in rows if n.startswith('_ZTV'))
    print(f'{len(objs)} engine data objects in the image; {len(rows)} defined natively ({vt} vtables) -> copied at '
          f'startup; {len(game_ia)} game static initializers')


if __name__ == '__main__':
    main()
