"""Generate adapters for the engine's virtual functions: the game calls them through vtable slots (rw::vcall), so the
address it lands on is a native vtable entry. -> out/gen/vt_adapters.cpp (khux_register_vtable_adapters)

python tools/gen_vtable_adapters.py

Signatures come from clang's -fdump-vtable-layouts of the engine (engine_diff.py's out/vt/all.txt); at startup the
runtime reads every class's vtable symbol (_ZTV...) and registers each entry's address with its adapter. An adapter
calls the entry through a member-function pointer built from that address (khux_target, set by the dispatcher), so
the member-call ABI is clang's. Entries whose types do not compile here are dropped (listed).
"""
import re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_adapters as G

ROOT = G.ROOT
OUT = G.OUT
DUMP = ROOT / 'out' / 'vt' / 'all.txt'


def classes():
    """{class: [(index, signature)]} - the first layout dumped per class."""
    out, cur, rows = {}, None, []
    for l in DUMP.read_text(errors='replace').splitlines():
        m = re.match(r"Vtable for '(.+)' \(\d+ entries\)\.", l)
        if m:
            cur, rows = m.group(1), []
            continue
        if cur is None: continue
        if not l.strip():
            out.setdefault(cur, rows); cur = None; continue
        m = re.match(r'\s*(\d+) \| (.*)$', l)
        if m: rows.append((int(m.group(1)), m.group(2)))
    return out


def mangle_class(name):
    if '<' in name or '(' in name: return None
    return 'N' + ''.join(f'{len(p)}{p}' for p in name.split('::')) + 'E' if '::' in name else f'{len(name)}{name}'


def parse(sig):
    """('dtor', cls, None) | ('fn', cls, 'R(P...)' , const) | None"""
    sig = re.sub(r'\s*\[[^\]]*\]', '', sig).strip()       # [complete] [deleting] [pure] [return adjustment ...]
    if sig.startswith(('offset_to_top', 'vcall_offset', 'vbase_offset')) or sig.endswith('RTTI'): return None
    const = sig.endswith(' const')
    if const: sig = sig[:-6]
    if not sig.endswith(')'): return None
    depth, i = 0, len(sig) - 1
    while i >= 0:
        if sig[i] == ')': depth += 1
        elif sig[i] == '(':
            depth -= 1
            if depth == 0: break
        i -= 1
    head, params = sig[:i], sig[i + 1:-1]
    # the qualified name is the last top-level token of head
    depth, j = 0, len(head) - 1
    while j >= 0:
        c = head[j]
        if c == '>': depth += 1
        elif c == '<': depth -= 1
        elif depth == 0 and c in ' *&': break
        j -= 1
    qual, ret = head[j + 1:], head[:j + 1].strip()
    if '::' not in qual: return None
    cls, leaf = qual.rsplit('::', 1)
    if leaf.startswith('~'): return ('dtor', cls, None, False)
    if not ret: return None
    return ('fn', cls, f'{ret}({params})', const)


HEADER = '''// Generated by tools/gen_vtable_adapters.py - do not edit. Adapters for the engine's virtual functions.
#include <unordered_map>
#include "adapt.hpp"
{includes}

using namespace cocos2d;
extern thread_local uint32_t khux_target;   // the native function being called (set by the dispatcher)

namespace {{
template <class C, class Sig> struct At;
template <class C, class R, class... P> struct At<C, R(P...)> {{
    static uint64_t run(const uint32_t *a, int n) {{
        R (C::*mf)(P...);
        uintptr_t w[2] = {{uintptr_t(khux_target), 0}};      // Itanium: {{function address, this adjustment}}
        std::memcpy(&mf, w, sizeof mf);
        return khux::adapt(mf, a, n);
    }}
}};
template <class C, class Sig> struct AtC;
template <class C, class R, class... P> struct AtC<C, R(P...)> {{
    static uint64_t run(const uint32_t *a, int n) {{
        R (C::*mf)(P...) const;
        uintptr_t w[2] = {{uintptr_t(khux_target), 0}};
        std::memcpy(&mf, w, sizeof mf);
        return khux::adapt(mf, a, n);
    }}
}};
uint64_t run_dtor(const uint32_t *a, int) {{                   // complete or deleting: this only
    reinterpret_cast<void(__attribute__((thiscall)) *)(void *)>(khux_target)(reinterpret_cast<void *>(uintptr_t(a[0])));
    return a[0];
}}
}}  // namespace
'''


def main():
    have = G.defined_symbols()
    cl = classes()
    adapters, index = [], {}
    slots = {}                                               # class -> [(entry index, adapter index)]
    ex = G.excluded()
    for cls, rows in cl.items():
        if ex and (cls + '::').startswith(ex): continue
        m = mangle_class(cls)
        if not m or f'_ZTV{m}' not in have: continue
        lst = []
        for idx, sig in rows:
            p = parse(sig)
            if not p: continue
            kind, c, s, const = p
            expr = 'run_dtor' if kind == 'dtor' else f'{"AtC" if const else "At"}<{c}, {s}>::run'
            if expr not in index:
                index[expr] = len(adapters); adapters.append(expr)
            lst.append((idx, index[expr]))
        slots[cls] = (m, lst)
    dropped = set()
    flags = G.compile_flags()
    for it in range(40):
        head = HEADER.format(includes='\n'.join(f'#include "{h}"' for h in G.INCLUDES)).splitlines()
        first = len(head) + 2
        body = ['', 'static const khux::Adapter kAdapters[] = {']
        body += [f'    {e},' if k not in dropped else '    nullptr,' for k, e in enumerate(adapters)]
        body += ['};', '']
        for k, (cls, (m, lst)) in enumerate(slots.items()):
            body.append(f'extern "C" const uint32_t vt{k}[] __asm__("__ZTV{m}");')
        body += ['', 'void khux_register_vtable_adapters(std::unordered_map<uint32_t, khux::Adapter> &map) {']
        for k, (cls, (m, lst)) in enumerate(slots.items()):
            pairs = ', '.join(f'{{{i}, {a}}}' for i, a in lst if a not in dropped)
            if pairs:
                body.append(f'    {{ static const uint16_t s[][2] = {{{pairs}}}; for (auto &e : s) '
                            f'if (vt{k}[e[0]] && kAdapters[e[1]]) map.emplace(vt{k}[e[0]], kAdapters[e[1]]); }}')
        body += ['}', '']
        src = OUT / 'vt_adapters.cpp'
        src.write_text('\n'.join(head + body), encoding='utf-8')
        r = subprocess.run([G.CXX] + flags + ['-c', str(src), '-o', str(OUT / 'vt_adapters.o'), '-ferror-limit=0'],
                           capture_output=True, text=True, cwd=str(G.ENGINE))
        if r.returncode == 0: break
        bad, why = set(), None
        for line in r.stderr.splitlines():
            if ': error:' in line:
                why = line
                if 'vt_adapters.cpp' not in line: continue
            mm = re.search(r'vt_adapters\.cpp:(\d+):\d+: (?:error|note)', line)
            if mm and why:
                k = int(mm.group(1)) - first - 1
                if 0 <= k < len(adapters): bad.add(k); why = None
        if not bad: sys.exit('compile failed outside the adapters:\n' + r.stderr[-3000:])
        dropped |= bad
    (OUT / 'vt_adapters_dropped.txt').write_text('\n'.join(adapters[k] for k in sorted(dropped)), encoding='utf-8')
    n_slots = sum(len([1 for i, a in lst if a not in dropped]) for m, lst in slots.values())
    print(f'{len(slots)} engine classes with vtables, {n_slots} vtable entries, {len(adapters) - len(dropped)} distinct '
          f'adapters compiled, {len(dropped)} dropped')


if __name__ == '__main__':
    main()
