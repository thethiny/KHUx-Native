"""Generate the import table: the game's import stubs (PLT) -> what a call to them runs natively.
-> out/gen/imports.cpp (khux_register_imports)

python tools/gen_imports.py

From recomp's analysis (out/analysis.json "plt", "init_array"): an internal stub (the function is in the image:
statically linked libc++ etc.) forwards to its target - a rewrite; an external one gets an adapter from the native
prototype (khux::adapt(&::name)) when the layouts match; functions passing Android structs (stat, time, dirent,
pthread attributes, sockets, ...) are left for hand-written implementations and listed with the rest that do not
compile in out/gen/imports_missing.txt (a call to one stops the game with its name).
"""
import json, re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_adapters as G

ROOT = G.ROOT
OUT = G.OUT
ANALYSIS = G.RECOMP / 'out' / 'analysis.json'
HAND = re.compile(r'^(stat|fstat|lstat|time|localtime|localtime_r|gmtime|gmtime_r|mktime|difftime|clock_gettime|'
                  r'gettimeofday|opendir|readdir|readdir_r|closedir|scandir|pthread_\w+|sem_\w+|sched_\w+|'
                  r'socket|connect|bind|accept|listen|send|recv|sendto|recvfrom|getaddrinfo|freeaddrinfo|'
                  r'gethostbyname|select|poll|setsockopt|getsockopt|ioctl|fcntl|fork|exec\w*|dl\w+|'
                  r'signal|bsd_signal|sigaction|mmap|munmap|__\w+|fopen|fdopen|freopen|fclose|fread|fwrite|fseek|'
                  r'ftell|fflush|fgets|fputs|fputc|fputwc|feof|ferror|rewind|setvbuf|open|close|read|write|lseek|'
                  r'mkdir|rmdir|unlink|rename|access|chdir|chmod|getcwd|remove)$')
# <cmath> overloads these on float / double: take the double one explicitly
LIBM1 = set('acos acosh asin asinh atan atanh cbrt ceil cos cosh erf erfc exp exp2 expm1 fabs floor lgamma log log10 '
            'log1p log2 logb nearbyint rint round sin sinh sqrt tan tanh tgamma trunc'.split())
LIBM2 = set('atan2 copysign fdim fmax fmin fmod hypot nextafter pow remainder'.split())
INCLUDES = ['cstdlib', 'cstring', 'cmath', 'cstdio', 'cctype', 'cwctype', 'cwchar', 'clocale', 'csetjmp', 'cerrno']


def main():
    a = json.loads(ANALYSIS.read_text())
    plt = {int(k, 16): v for k, v in a['plt'].items()}
    internal = [(k, int(v['target'], 16), v['name']) for k, v in plt.items() if v['target']]
    external = sorted({v['name']: k for k, v in plt.items() if not v['target']}.items())
    all_ext = sorted((k, v['name']) for k, v in plt.items() if not v['target'])   # every stub (a name can have several)
    gen = [(n, s) for n, s in external if not HAND.match(n) and not n.startswith(('gl', 'egl', 'AAsset', 'ANative',
                                                                                    'AConfiguration', 'ALooper', 'sl'))]
    dropped = set()
    for it in range(20):
        head = ['// Generated by tools/gen_imports.py - do not edit. The game\'s import stubs, natively.',
                '#include <unordered_map>', '#include "adapt.hpp"'] + [f'#include <{h}>' for h in INCLUDES]
        first = len(head) + 2
        body = ['', 'static const khux::AdapterEntry kExternal[] = {']
        def target(n):
            if n in LIBM1: return f'static_cast<double (*)(double)>(&::{n})'
            if n in LIBM2: return f'static_cast<double (*)(double, double)>(&::{n})'
            return f'&::{n}'
        body += [f'    {{0x{s:X}, [](const uint32_t *a, int n) -> uint64_t {{ return khux::adapt({target(n)}, a, n); }}, "{n}"}},'
                 for s, n in all_ext if n in dict(gen) and n not in dropped]
        body += ['    {0, nullptr, nullptr}', '};']
        body += ['static const uint32_t kInternal[][2] = {'] + [f'    {{0x{s:X}, 0x{t:X}}},' for s, t, n in internal] + ['};']
        body += ['static const struct { uint32_t stub; const char *name; } kAll[] = {']
        body += [f'    {{0x{s:X}, "{n}"}},' for s, n in all_ext] + ['};']
        body += [f'static const uint32_t kInit[] = {{{", ".join(a["init_array"])}}};']
        body += ['extern "C" void khux_image_set_import_stub(const char *name, uint32_t stub);',
                 'extern "C" const uint32_t *khux_init_array(int *count) { *count = int(sizeof kInit / 4); return kInit; }',
                 'extern "C" const char *khux_import_name(uint32_t stub) {',
                 '    for (auto &e : kAll) if (e.stub == stub) return e.name;',
                 '    return nullptr;', '}',
                 'extern "C" void khux_for_each_import(void (*f)(uint32_t stub, const char *name, void *ctx), void *ctx) {',
                 '    for (auto &e : kAll) f(e.stub, e.name, ctx);', '}',
                 'void khux_register_imports(std::unordered_map<uint32_t, khux::Adapter> &native, std::unordered_map<uint32_t, uint32_t> &alias) {',
                 '    for (auto &e : kExternal) if (e.fn) native[e.addr] = e.fn;',
                 '    for (auto &e : kInternal) alias[e[0]] = e[1];',
                 '    for (auto &e : kAll) khux_image_set_import_stub(e.name, e.stub);', '}', '']
        src = OUT / 'imports.cpp'
        src.write_text('\n'.join(head + body), encoding='utf-8')
        r = subprocess.run([G.CXX, '-std=gnu++17', '-O1', '-w', f'-I{ROOT / "src"}', '-c', str(src), '-o', str(OUT / 'imports.o'),
                            '-ferror-limit=0'], capture_output=True, text=True)
        if r.returncode == 0: break
        bad, why = set(), None
        live = [n for s, n in all_ext if n in dict(gen) and n not in dropped]
        for line in r.stderr.splitlines():
            if ': error:' in line:
                why = line
                if 'imports.cpp' not in line: continue
            mm = re.search(r'imports\.cpp:(\d+):\d+: (?:error|note)', line)
            if mm and why:
                k = int(mm.group(1)) - first - 1
                if 0 <= k < len(live): bad.add(live[k]); why = None
        if not bad: sys.exit('compile failed outside the entries:\n' + r.stderr[-2500:])
        dropped |= bad
    made = [n for n, s in gen if n not in dropped]
    rest = [n for n, s in external if n not in made]
    (OUT / 'imports_missing.txt').write_text('\n'.join(rest), encoding='utf-8')
    print(f'{len(plt)} import stubs: {len(internal)} internal (forward to a rewrite), {len(external)} external - '
          f'{len(made)} adapters from native prototypes, {len(rest)} left for hand-written ones')


if __name__ == '__main__':
    main()
